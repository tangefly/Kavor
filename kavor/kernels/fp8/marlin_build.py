import fcntl
import hashlib
import os
import sys
from pathlib import Path

import torch

from kavor.utils.logger import logger

CSRC = Path(__file__).resolve().parents[2] / "csrc" / "quantization" / "marlin"
REPO_ROOT = Path(__file__).resolve().parents[3]
_EXT_PREFIX = "kavor_marlin"

_ops = None
_failure: Exception | None = None


def _use_repo_cache() -> None:
    """Keep the JIT build in the checkout's .cache (git-ignored) instead of ~/.cache.
    """
    if not (REPO_ROOT / "setup.py").is_file():
        return
    tag = getattr(sys, "abiflags", "")
    cuda = (torch.version.cuda or "").replace(".", "")
    cache = REPO_ROOT / ".cache" / "torch_extensions" / (
        f"py{sys.version_info.major}{sys.version_info.minor}{tag}_cu{cuda}"
    )
    cache.mkdir(parents=True, exist_ok=True)
    os.environ.setdefault("TORCH_EXTENSIONS_DIR", str(cache))


def is_disabled() -> bool:
    return os.environ.get("KAVOR_MARLIN_DISABLE", "") not in ("", "0")


def _sources() -> list[str]:
    generated = sorted(CSRC.glob("*kernel_*.cu"))
    if not generated:
        raise RuntimeError(
            f"No *kernel_*.cu found under {CSRC}; run "
            "python csrc/quantization/marlin/generate_kernels.py 8.0 first")
    return [
        str(CSRC / "marlin.cu"),
        str(CSRC / "gptq_marlin_repack.cu"),
        *map(str, generated),
    ]


def _device_cc() -> tuple[int, int]:
    major, minor = torch.cuda.get_device_capability()
    return major, minor


def _arch_flags() -> list[str]:
    """Emit cubin for the current device; other than SM80, also embed an 8.0 PTX.

    The extra PTX keeps one build usable across the whole architecture family.
    """
    major, minor = _device_cc()
    cc = f"{major}{minor}"
    flags = [f"-gencode=arch=compute_{cc},code=sm_{cc}"]
    if cc != "80":
        flags.append("-gencode=arch=compute_80,code=compute_80")
    return flags


def _source_hash() -> str:
    h = hashlib.sha256()
    for path in sorted(CSRC.rglob("*")):
        if path.is_dir() or path.suffix in (".pyc", ".md"):
            continue
        if path.name in ("LICENSE.vllm",):
            continue
        h.update(path.relative_to(CSRC).as_posix().encode())
        h.update(path.read_bytes())
    h.update(torch.__version__.encode())
    h.update((torch.version.cuda or "").encode())
    h.update(f"{_device_cc()}".encode())
    h.update(" ".join(_arch_flags()).encode())
    return h.hexdigest()[:12]


def _extension_name() -> str:
    major, minor = _device_cc()
    return f"{_EXT_PREFIX}_{major}{minor}_{_source_hash()}"


def _build() -> None:
    from torch.utils.cpp_extension import _get_build_directory, load

    _use_repo_cache()
    name = _extension_name()
    build_dir = Path(_get_build_directory(name, verbose=False))
    build_dir.mkdir(parents=True, exist_ok=True)
    lock_path = build_dir / ".kavor_build.lock"

    cuda_flags = [
        "-O3",
        "--use_fast_math",
        "-std=c++17",
        # Marlin's kernel instantiations live in the *.cu files generated by
        # generate_kernels.py; the main TU only references the symbols. nvcc 12+
        # marks template stubs static by default, which breaks cross-TU linking.
        "-static-global-template-stub=false",
        *_arch_flags(),
    ]
    verbose = os.environ.get("KAVOR_MARLIN_VERBOSE", "") not in ("", "0")

    with open(lock_path, "w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        try:
            load(
                name=name,
                sources=_sources(),
                extra_include_paths=[str(CSRC)],
                extra_cuda_cflags=cuda_flags,
                extra_cflags=["-O3", "-std=c++17"],
                is_python_module=False,
                verbose=verbose,
            )
        finally:
            fcntl.flock(lock, fcntl.LOCK_UN)

    logger.info("Marlin extension ready: %s", name)


def load_marlin():
    """Return the loaded ``torch.ops.kavor_marlin``; a failure is cached and re-raised."""
    global _ops, _failure
    if _ops is not None:
        return _ops
    if _failure is not None:
        raise _failure
    if is_disabled():
        _failure = RuntimeError("KAVOR_MARLIN_DISABLE is set, Marlin unavailable")
        raise _failure
    if not torch.cuda.is_available():
        _failure = RuntimeError("Marlin requires CUDA")
        raise _failure
    try:
        _build()
        _ops = torch.ops.kavor_marlin
    except Exception as exc:  # noqa: BLE001 - a build failure becomes "kernel unavailable"
        _failure = exc
        raise
    return _ops


def marlin_available() -> tuple[bool, str]:
    """Queried by the registry; a build failure is recorded instead of raised."""
    try:
        load_marlin()
    except Exception as exc:  # noqa: BLE001
        return False, f"Marlin extension unavailable: {exc}"
    return True, ""


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if "--precompile" not in argv:
        print("Usage: python -m kavor.kernels.fp8.marlin_build --precompile")
        return 2
    try:
        load_marlin()
    except Exception as exc:  # noqa: BLE001
        print(f"Precompile failed: {exc}", file=sys.stderr)
        return 1
    print("Marlin precompile done")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
